# reflex_engine.py — 升級版
# 修復：
#   1. 所有回應改為繁體中文（原本有簡體混入）
#   2. 回應更自然、有個性（不要每次都「你好。」）
#   3. 擴充更多常見問句的快速回應（減少等 LLM 的時間）

import random


class ReflexEngine:
    """
    反射引擎：處理常見問句，不需要經過 LLM，速度極快
    原則：只處理「不需要思考就能回」的問題
    """

    def analyze(self, text: str):
        t = text.strip()
        tl = t.lower()

        # ── 問候 ────────────────────────────────────────────────────────────
        greetings = ["你好", "嗨", "哈囉", "hi", "hello", "嘿", "hey"]
        if any(g in tl for g in greetings) and len(t) <= 6:
            return random.choice([
                "嗨，有什麼需要我幫忙的？",
                "你好，說吧。",
                "嗨！",
            ])

        # ── 身份詢問 ─────────────────────────────────────────────────────────
        identity = ["你是誰", "你叫什麼", "你叫甚麼", "你的名字", "介紹一下你自己"]
        if any(i in t for i in identity):
            return random.choice([
                "我是立，你的本地 AI 系統核心。",
                "叫我立就好，專門幫你管這套 AI 系統的。",
            ])

        # ── 在不在 ───────────────────────────────────────────────────────────
        if "在嗎" in t or "你在嗎" in t:
            return "在，說。"

        # ── 能力詢問 ─────────────────────────────────────────────────────────
        capability = ["你能做什麼", "你會做什麼", "你可以做什麼", "你能幫我做什麼",
                      "你會什麼", "你有什麼功能", "你可以幫我"]
        if any(c in t for c in capability):
            return (
                "我主要能幫你：寫程式和修 bug、管理這套 AI 系統、"
                "回答技術問題、執行系統指令。"
                "直接說你要做什麼，我來處理。"
            )

        # ── 謝謝 ─────────────────────────────────────────────────────────────
        thanks = ["謝謝", "感謝", "thank", "thanks", "多謝"]
        if any(t2 in tl for t2 in thanks):
            return random.choice([
                "不客氣。",
                "好的，有需要繼續說。",
                "沒事。",
            ])

        # ── 再見 ─────────────────────────────────────────────────────────────
        bye = ["掰掰", "再見", "bye", "拜拜", "晚安", "掰"]
        if any(b in tl for b in bye):
            return random.choice([
                "掰掰，系統繼續在背景跑。",
                "再見。",
            ])

        # ── 測試 ─────────────────────────────────────────────────────────────
        if t in ["test", "測試", "ping"]:
            return "pong，系統正常。"

        # ── 超短輸入（不是有意義的問句）────────────────────────────────────
        if len(t) <= 2:
            return None

        return None
